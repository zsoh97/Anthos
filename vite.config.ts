import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';

function walkFiles(dir: string): string[] {
  const results: string[] = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      results.push(...walkFiles(full));
    } else {
      results.push(full);
    }
  }
  return results;
}

function anthosPwaPlugin(): Plugin {
  let outDir = 'dist';

  return {
    name: 'anthos-pwa-sw',
    apply: 'build',
    configResolved(config) {
      outDir = config.build.outDir;
    },
    closeBundle() {
      const files = walkFiles(outDir);
      const precacheUrls = new Set<string>(['/']);
      const hash = createHash('sha256');

      for (const file of files) {
        const rel = '/' + relative(outDir, file).replace(/\\/g, '/');
        if (rel === '/sw.js') continue;
        // Pre-cache app shell, icons, manifest, and built JS/CSS bundles;
        // watercolor plates in /plates/ are cached on demand in a persistent cache.
        if (!rel.startsWith('/plates/')) {
          precacheUrls.add(rel);
          hash.update(rel);
          hash.update(readFileSync(file));
        }
      }

      const version = hash.digest('hex').slice(0, 10);
      const shellCache = `anthos-shell-${version}`;
      const platesCache = 'anthos-plates-v1';
      const fontsCache = 'anthos-fonts-v1';
      const precacheList = JSON.stringify(Array.from(precacheUrls).sort(), null, 2);

      const swSource = `// Auto-generated by Vite build (version ${version})
const SHELL_CACHE = ${JSON.stringify(shellCache)};
const PLATES_CACHE = ${JSON.stringify(platesCache)};
const FONTS_CACHE = ${JSON.stringify(fontsCache)};
const PRECACHE_URLS = ${precacheList};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(SHELL_CACHE)
      .then((cache) => cache.addAll(PRECACHE_URLS))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  const keep = new Set([SHELL_CACHE, PLATES_CACHE, FONTS_CACHE]);
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((k) => !keep.has(k)).map((k) => caches.delete(k)))
      )
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);

  // Google Fonts: stale-while-revalidate for offline book typography
  if (
    url.origin === 'https://fonts.googleapis.com' ||
    url.origin === 'https://fonts.gstatic.com'
  ) {
    event.respondWith(
      caches.open(FONTS_CACHE).then(async (cache) => {
        const cached = await cache.match(request);
        const networkPromise = fetch(request)
          .then((response) => {
            if (response.ok) cache.put(request, response.clone());
            return response;
          })
          .catch(() => cached);
        return cached || networkPromise;
      })
    );
    return;
  }

  if (url.origin !== self.location.origin) return;

  // Navigation requests: network-first so updates land immediately, offline fallback to cached shell
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok && url.pathname === '/' && !url.search) {
            const copy = response.clone();
            caches.open(SHELL_CACHE).then((cache) => cache.put('/index.html', copy));
          }
          return response;
        })
        .catch(async () => {
          const cache = await caches.open(SHELL_CACHE);
          return (await cache.match('/index.html')) || (await cache.match('/'));
        })
    );
    return;
  }

  // Watercolor plates: cache-first in a persistent cache across code deploys
  if (url.pathname.startsWith('/plates/')) {
    event.respondWith(
      caches.open(PLATES_CACHE).then(async (cache) => {
        const cached = await cache.match(request);
        if (cached) return cached;
        const response = await fetch(request);
        if (response.ok) cache.put(request, response.clone());
        return response;
      })
    );
    return;
  }

  // App shell & hashed assets: cache-first, falling back to network
  event.respondWith(
    caches.open(SHELL_CACHE).then(async (cache) => {
      const cached = await cache.match(request);
      if (cached) return cached;
      const response = await fetch(request);
      if (response.ok) cache.put(request, response.clone());
      return response;
    })
  );
});
`;

      writeFileSync(join(outDir, 'sw.js'), swSource, 'utf8');
    },
  };
}

export default defineConfig({
  plugins: [react(), tailwindcss(), anthosPwaPlugin()],
  server: {
    port: 5173,
    host: true,
  },
});
